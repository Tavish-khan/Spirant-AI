<?php

declare(strict_types=1);

require_once __DIR__ . '/AIService.php';

class MockAIService extends AIService
{
    public function generateTextResponse(string $prompt, ?array $context = null): string
    {
        $normalized = strtolower(trim($prompt));

        if ($normalized === '') {
            return 'I am ready to help. Please share your question or idea.';
        }

        if (str_contains($normalized, 'email')) {
            return "Here is a polished draft you can use: \n\nSubject: Follow-up on our recent discussion\n\nHi there,\n\nThank you for your time and for the opportunity to discuss this matter. I appreciate your perspective and believe we can move forward with a clear and effective plan. Please let me know if you would like to review the next steps together.\n\nBest regards,\nSpirant AI";
        }

        if (str_contains($normalized, 'code') || str_contains($normalized, 'php') || str_contains($normalized, 'program')) {
            return "I can help with coding tasks. In a real AI integration, I would inspect your codebase, propose a fix, and provide maintainable logic. For Phase 1, here is a mock answer: start by separating concerns, validate input on the server, and structure your project with reusable backend services and clear API endpoints.";
        }

        if (str_contains($normalized, 'image') || str_contains($normalized, 'analy')) {
            return 'I can analyze uploaded images in the future via a vision-capable AI API. For Phase 1, the image flow is fully prepared and stored securely, and the mock analysis layer is ready to be replaced with a real model integration.';
        }

        if (str_contains($normalized, 'business') || str_contains($normalized, 'idea') || str_contains($normalized, 'strategy')) {
            return 'A strong strategy starts with clarity, validation, and measurable outcomes. Define the problem, identify the customer segment, test a small solution, and refine based on real feedback before scaling. Spirant AI can support that process with structured prompts, planning support, and generation workflows.';
        }

        return "This is a Phase 1 mock AI response generated by Spirant AI. The architecture is ready for a real API connection later, and the backend is structured so the model can be swapped without rewriting the frontend or database flow.\n\nYour prompt was: \"" . htmlspecialchars($prompt, ENT_QUOTES, 'UTF-8') . "\"\n\nIf you want, I can also help with content writing, brainstorming, technical analysis, or product planning.";
    }

    public function generateImageResponse(string $imagePath, string $question): string
    {
        $questionText = trim($question);

        if ($questionText === '') {
            $questionText = 'Describe this image';
        }

        $fileName = basename($imagePath);

        return "Mock image analysis for: {$fileName}\n\nThe uploaded image has been validated and stored successfully. In Phase 2, this will be replaced by a vision AI model that can interpret the actual image contents and answer questions such as: \"{$questionText}\". For now, the application correctly handles upload validation, metadata storage, and conversation association.";
    }
}
